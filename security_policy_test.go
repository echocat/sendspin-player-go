func TestLongTermPairingSecretGenerationUsesCSPRNG(t *testing.T) {
	_, here, _, _ := runtime.Caller(0)
	f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(filepath.Dir(here), "session.go"), nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	imported, draw := false, false
	for _, i := range f.Imports {
		if i.Path.Value == `"crypto/rand"` && i.Name == nil {
			imported = true
		}
	}
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Name.Name != "activate" {
			continue
		}
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) != 1 {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok || sel.Sel.Name != "Read" {
				return true
			}
			pkg, ok := sel.X.(*ast.Ident)
			if !ok || pkg.Name != "rand" {
				return true
			}
			slice, ok := call.Args[0].(*ast.SliceExpr)
			if !ok {
				return true
			}
			id, ok := slice.X.(*ast.Ident)
			draw = ok && id.Name == "psk"
			return true
		})
	}
	if !imported || !draw {
		t.Fatal("long-term secret is no longer generated by crypto/rand")
	}
}

func TestSDKImportsOnlyTheLoggingFacade(t *testing.T) {
	_, here, _, _ := runtime.Caller(0)
	root := filepath.Dir(here)
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, e error) error {
		if e != nil {
			return e
		}
		if d.IsDir() {
			if d.Name() == "var" || d.Name() == ".git" || d.Name() == ".idea" || d.Name() == "_examples" {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		f, e := parser.ParseFile(token.NewFileSet(), path, nil, parser.ImportsOnly)
		if e != nil {
			return e
		}
		for _, i := range f.Imports {
			name, _ := strconv.Unquote(i.Path.Value)
			if strings.HasPrefix(name, "github.com/echocat/slf4g/") || name == "log" || name == "log/slog" {
				t.Errorf("SDK uses a logging implementation instead of facade: %s: %s", path, name)
			}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}
