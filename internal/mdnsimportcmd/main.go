// Command mdnsimportcmd reproducibly imports/checks the pinned scoped mDNS fork.
// Default is verification only; --write explicitly regenerates imported files.
package main

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"
)

const revision = "586e7c571d106f842c8567012dacd28d73fcf966"

var sources = map[string]string{
	"client.go":     "9b2ab526cd4affb7b881a714266dc1d25647db10c5118fbde4a6f61d10e1bc2f",
	"server.go":     "6ec7975552a54143cac70b37e73b7728abc79d7b5167e981c6b425b4e01c010b",
	"connection.go": "91d7e915947aff151932a4f656c62af2e44b7ade2400293b9d76ef453177de86",
	"service.go":    "e6a208f8c02adfd2b76189c90962868bc55cc4bcdc1f1c902d9b8588dadd3f77",
	"utils.go":      "359c990e3a52dba8a20f3b8836cfb2030b11d151af7fefe9cdf182139f9732b1",
	"LICENSE":       "200e14ba92ed9bee1273b522c0931351bfb89c41177056e5d0cafc7e91e45c0a",
}

func replace(raw, old, next string, count int) (string, error) {
	if strings.Count(raw, old) != count {
		return "", fmt.Errorf("mDNS patch anchor count differs: %q", old)
	}
	return strings.ReplaceAll(raw, old, next), nil
}

func adapt(name string, data []byte) ([]byte, error) {
	if name == "LICENSE" {
		lines := strings.Split(string(data), "\n")
		for i := range lines {
			lines[i] = strings.TrimRight(lines[i], " \t\r")
		}
		return []byte(strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n"), nil
	}
	raw := string(data)
	var err error
	raw, err = replace(raw, "package zeroconf", "package mdns", 1)
	if err != nil {
		return nil, err
	}
	// Imported transport diagnostics use the SDK facade and no raw service,
	// interface, address or error values. Preserve the surrounding error paths.
	raw = strings.ReplaceAll(raw, "\t\"log\"\n", "")
	raw = strings.ReplaceAll(raw, "import \"log\"\n", "")
	lines := strings.Split(raw, "\n")
	for i, line := range lines {
		if strings.Contains(line, "log.Printf(") || strings.Contains(line, "log.Println(") {
			if strings.HasPrefix(strings.TrimSpace(line), "//") {
				continue
			}
			indent := line[:len(line)-len(strings.TrimLeft(line, "\t"))]
			lines[i] = indent + `logger.Debug("mDNS transport operation unavailable")`
		}
	}
	raw = strings.Join(lines, "\n")
	// Private wrappers retain x/net behavior on Unix and provide packet-info
	// through the standard Go UDP API on Windows (x/net does not implement it).
	raw = strings.ReplaceAll(raw, "*ipv4.PacketConn", "*packetConn4")
	raw = strings.ReplaceAll(raw, "*ipv6.PacketConn", "*packetConn6")
	raw = strings.ReplaceAll(raw, "ipv4.NewPacketConn(udpConn)", "newPacketConn4(udpConn)")
	raw = strings.ReplaceAll(raw, "ipv6.NewPacketConn(udpConn)", "newPacketConn6(udpConn)")
	if name == "server.go" {
		for _, anchor := range []string{
			"func (s *Server) parsePacket(packet []byte, ifIndex int, from net.Addr) error {",
			"func (s *Server) handleQuery(query *dns.Msg, ifIndex int, from net.Addr) error {",
		} {
			raw, err = replace(raw, anchor, anchor+"\n\tif !scopeAllowed(ifIndex, s.ifaces) { return nil }", 1)
			if err != nil {
				return nil, err
			}
		}
	}
	if name == "client.go" {
		raw, err = replace(raw, "var readFrom func([]byte) (n int, src net.Addr, err error)", "var readFrom func([]byte) (n int, src net.Addr, ifIndex int, err error)", 1)
		if err != nil {
			return nil, err
		}
		raw, err = replace(raw, "func(b []byte) (n int, src net.Addr, err error)", "func(b []byte) (n int, src net.Addr, ifIndex int, err error)", 2)
		if err != nil {
			return nil, err
		}
		raw, err = replace(raw, "n, _, src, err = pConn.ReadFrom(b)\n\t\t\treturn", "n, cm, from, readErr := pConn.ReadFrom(b)\n\t\t\tif cm != nil { ifIndex = cm.IfIndex }; return n, from, ifIndex, readErr", 2)
		if err != nil {
			return nil, err
		}
		raw, err = replace(raw, "n, _, err := readFrom(buf)", "n, _, ifIndex, err := readFrom(buf)", 1)
		if err != nil {
			return nil, err
		}
		raw, err = replace(raw, "msg := new(dns.Msg)", "if !scopeAllowed(ifIndex, c.ifaces) { continue }; msg := new(dns.Msg)", 1)
		if err != nil {
			return nil, err
		}
	}
	if name == "connection.go" {
		for _, family := range []string{"ipv4", "ipv6"} {
			anchor := "pkConn.SetControlMessage(" + family + ".FlagInterface, true)"
			raw, err = replace(raw, anchor, "if err := "+anchor+"; err != nil { _ = pkConn.Close(); return nil, fmt.Errorf(\"mDNS: packet interface metadata unavailable: %w\", err) }", 1)
			if err != nil {
				return nil, err
			}
		}
	}
	raw = "// Code generated by internal/mdnsimportcmd from libp2p/zeroconf " + revision + "; DO NOT EDIT.\n// MIT license and upstream copyrights: see LICENSE in this directory.\n\n" + raw
	return format.Source([]byte(raw))
}

func run(ctx context.Context, write bool) error {
	client := &http.Client{Timeout: 30 * time.Second}
	generated := map[string][]byte{}
	for name, expected := range sources {
		req, err := http.NewRequestWithContext(ctx, http.MethodGet, "https://raw.githubusercontent.com/libp2p/zeroconf/"+revision+"/"+name, nil)
		if err != nil {
			return err
		}
		response, err := client.Do(req)
		if err != nil {
			return err
		}
		data, readErr := io.ReadAll(io.LimitReader(response.Body, 128<<10))
		closeErr := response.Body.Close()
		if readErr != nil {
			return readErr
		}
		if closeErr != nil {
			return closeErr
		}
		sum := sha256.Sum256(data)
		if response.StatusCode != http.StatusOK || hex.EncodeToString(sum[:]) != expected {
			return fmt.Errorf("pinned mDNS source unavailable/changed: %s", name)
		}
		generated[name], err = adapt(name, data)
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
	}
	for name, data := range generated {
		path := filepath.Join("internal", "mdns", name)
		if write {
			if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
				return err
			}
			if err := os.WriteFile(path, data, 0644); err != nil {
				return err
			}
		} else {
			actual, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			actual = bytes.ReplaceAll(actual, []byte("\r\n"), []byte("\n"))
			if !bytes.Equal(actual, data) {
				return errors.New("imported mDNS source differs: " + path)
			}
		}
	}
	return nil
}

func main() {
	write := flag.Bool("write", false, "Explicitly regenerate imported upstream files")
	flag.Parse()
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	if err := run(ctx, *write); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("Pinned mDNS sources and scoped transformation verified.")
}
